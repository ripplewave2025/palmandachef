const textNodes = document.querySelectorAll("[data-i18n]");
const htmlNodes = document.querySelectorAll("[data-i18n-html]");
const langButtons = document.querySelectorAll(".lang-chip");
const locationButtons = document.querySelectorAll(".location-pill");
const locationName = document.getElementById("locationName");
const locationDescription = document.getElementById("locationDescription");
const navToggle = document.getElementById("navToggle");
const navPanel = document.getElementById("navPanel");
const siteHeader = document.getElementById("siteHeader");

let activeLang = localStorage.getItem("palman-language") || "en";
let activeLocation = "darjeeling";

const applyLanguage = (lang) => {
  activeLang = portfolioCopy[lang] ? lang : "en";
  const copy = portfolioCopy[activeLang];

  document.documentElement.lang = copy.lang;

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) {
      node.textContent = copy[key];
    }
  });

  htmlNodes.forEach((node) => {
    const key = node.dataset.i18nHtml;
    if (copy[key]) {
      node.innerHTML = copy[key];
    }
  });

  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === activeLang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  renderLocations(copy);
  localStorage.setItem("palman-language", activeLang);
};

const renderLocations = (copy) => {
  locationButtons.forEach((button) => {
    const key = button.dataset.location;
    const location = copy.locations[key];
    button.textContent = location.name;
    button.classList.toggle("is-active", key === activeLocation);
  });

  const activeData = copy.locations[activeLocation];
  locationName.textContent = activeData.name;
  locationDescription.textContent = activeData.description;
};

langButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

locationButtons.forEach((button) => {
  button.addEventListener("click", () => {
    activeLocation = button.dataset.location;
    renderLocations(portfolioCopy[activeLang] || portfolioCopy.en);
  });
});

const setNavOpen = (open) => {
  siteHeader.classList.toggle("nav-open", open);
  document.body.classList.toggle("nav-open", open);
  navToggle.setAttribute("aria-expanded", String(open));
  if (!open) {
    navPanel.scrollTop = 0;
  }
};

navToggle.addEventListener("click", () => {
  const open = navToggle.getAttribute("aria-expanded") !== "true";
  setNavOpen(open);
});

document.querySelectorAll(".nav-links a").forEach((link) => {
  link.addEventListener("click", () => setNavOpen(false));
});

window.addEventListener(
  "scroll",
  () => {
    siteHeader.classList.toggle("is-scrolled", window.scrollY > 12);
  },
  { passive: true }
);

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.14 }
);

document.querySelectorAll("[data-reveal]").forEach((node) => {
  revealObserver.observe(node);
});

document.addEventListener("pointermove", (event) => {
  document.documentElement.style.setProperty("--pointer-x", `${event.clientX}px`);
  document.documentElement.style.setProperty("--pointer-y", `${event.clientY}px`);
});

if (window.matchMedia("(pointer: fine)").matches) {
  document.querySelectorAll(".tilt-card").forEach((card) => {
    card.addEventListener("pointermove", (event) => {
      const rect = card.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - 0.5;
      const y = (event.clientY - rect.top) / rect.height - 0.5;

      card.style.setProperty("--rotate-x", `${(-y * 8).toFixed(2)}deg`);
      card.style.setProperty("--rotate-y", `${(x * 10).toFixed(2)}deg`);
      card.style.setProperty("--lift-y", "-4px");
    });

    card.addEventListener("pointerleave", () => {
      card.style.removeProperty("--rotate-x");
      card.style.removeProperty("--rotate-y");
      card.style.removeProperty("--lift-y");
    });
  });

  document.querySelectorAll(".magnetic").forEach((button) => {
    button.addEventListener("pointermove", (event) => {
      const rect = button.getBoundingClientRect();
      const x = ((event.clientX - rect.left) / rect.width - 0.5) * 8;
      const y = ((event.clientY - rect.top) / rect.height - 0.5) * 8;
      button.style.transform = `translate(${x}px, ${y}px)`;
    });

    button.addEventListener("pointerleave", () => {
      button.style.transform = "";
    });
  });
}

