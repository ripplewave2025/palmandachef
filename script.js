const textNodes = document.querySelectorAll("[data-i18n]");
const languageMenu = document.getElementById("languageMenu");
const languageTrigger = document.getElementById("languageTrigger");
const languageOptions = document.querySelectorAll(".language-option");
const menuButton = document.getElementById("menuButton");
const menuPanel = document.getElementById("menuPanel");
const topbar = document.getElementById("topbar");
const serviceTabs = document.querySelectorAll(".service-tab");
const serviceFields = document.querySelectorAll("[data-service-field]");
const servicePoints = document.querySelectorAll("[data-service-point]");
const revealNodes = document.querySelectorAll("[data-reveal]");
const magneticNodes = document.querySelectorAll(".magnetic");

let activeLang = localStorage.getItem("palman-language") || "en";
let activeService = "grill";

const setMenuOpen = (open) => {
  document.body.classList.toggle("menu-open", open);
  menuButton.setAttribute("aria-expanded", String(open));
};

const setLanguageOpen = (open) => {
  languageMenu.classList.toggle("is-open", open);
  languageTrigger.setAttribute("aria-expanded", String(open));
};

const getDictionary = (lang) => content[lang] || content.en;

const renderService = (serviceKey) => {
  const dictionary = getDictionary(activeLang);
  const serviceData = dictionary.serviceData?.[serviceKey] || content.en.serviceData[serviceKey];

  if (!serviceData) {
    return;
  }

  serviceFields.forEach((field) => {
    const key = field.dataset.serviceField;
    field.textContent = serviceData[key] || "";
  });

  servicePoints.forEach((point, index) => {
    point.textContent = serviceData.points[index] || "";
  });

  serviceTabs.forEach((tab) => {
    const isActive = tab.dataset.service === serviceKey;
    tab.classList.toggle("is-active", isActive);
    tab.setAttribute("aria-selected", String(isActive));
  });
};

const applyLanguage = (lang) => {
  activeLang = content[lang] ? lang : "en";
  const dictionary = getDictionary(activeLang);

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  languageOptions.forEach((option) => {
    const isActive = option.dataset.lang === activeLang;
    option.classList.toggle("is-active", isActive);
    option.setAttribute("aria-checked", String(isActive));
  });

  document.documentElement.lang = activeLang === "dz" ? "dz" : activeLang;
  localStorage.setItem("palman-language", activeLang);
  renderService(activeService);
};

languageTrigger.addEventListener("click", () => {
  const next = languageTrigger.getAttribute("aria-expanded") !== "true";
  setMenuOpen(false);
  setLanguageOpen(next);
});

languageOptions.forEach((option) => {
  option.addEventListener("click", () => {
    applyLanguage(option.dataset.lang);
    setLanguageOpen(false);
  });
});

menuButton.addEventListener("click", () => {
  const next = menuButton.getAttribute("aria-expanded") !== "true";
  setLanguageOpen(false);
  setMenuOpen(next);
});

document.querySelectorAll(".menu-panel a[href^='#']").forEach((link) => {
  link.addEventListener("click", () => setMenuOpen(false));
});

serviceTabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    activeService = tab.dataset.service;
    renderService(activeService);
  });
});

window.addEventListener(
  "scroll",
  () => {
    topbar.classList.toggle("is-scrolled", window.scrollY > 8);
  },
  { passive: true }
);

document.addEventListener("click", (event) => {
  if (!languageMenu.contains(event.target)) {
    setLanguageOpen(false);
  }

  if (!menuPanel.contains(event.target) && !menuButton.contains(event.target)) {
    setMenuOpen(false);
  }
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    setLanguageOpen(false);
    setMenuOpen(false);
  }
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
      }
    });
  },
  { threshold: 0.18 }
);

revealNodes.forEach((node) => revealObserver.observe(node));

if (window.matchMedia("(pointer: fine)").matches) {
  magneticNodes.forEach((node) => {
    node.addEventListener("pointermove", (event) => {
      const bounds = node.getBoundingClientRect();
      const offsetX = ((event.clientX - bounds.left) / bounds.width - 0.5) * 10;
      const offsetY = ((event.clientY - bounds.top) / bounds.height - 0.5) * 10;
      node.style.transform = `translate(${offsetX}px, ${offsetY}px)`;
    });

    node.addEventListener("pointerleave", () => {
      node.style.transform = "";
    });
  });
}

